CREATE TABLE users (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(50) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(16) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE, must_change BOOLEAN NOT NULL DEFAULT TRUE,
 auth_version INT NOT NULL DEFAULT 0
);
CREATE TABLE departments (id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL);
CREATE TABLE majors (id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL, department_id BIGINT NOT NULL, FOREIGN KEY(department_id) REFERENCES departments(id));
CREATE TABLE classes (id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL, major_id BIGINT NOT NULL, FOREIGN KEY(major_id) REFERENCES majors(id));
CREATE TABLE students (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, full_name VARCHAR(150) NOT NULL,
 email VARCHAR(150), phone VARCHAR(20), birth_date DATE, gender VARCHAR(12) NOT NULL DEFAULT 'OTHER',
 class_id BIGINT NOT NULL, status VARCHAR(16) NOT NULL DEFAULT 'STUDYING', user_id BIGINT UNIQUE,
 FOREIGN KEY(class_id) REFERENCES classes(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE teachers (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, full_name VARCHAR(150) NOT NULL,
 email VARCHAR(150), phone VARCHAR(20), department_id BIGINT NOT NULL, user_id BIGINT UNIQUE,
 FOREIGN KEY(department_id) REFERENCES departments(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE subjects (id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL, credits INT NOT NULL);
CREATE TABLE semesters (id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL, starts_on DATE NOT NULL, ends_on DATE NOT NULL);
CREATE TABLE sections (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(30) NOT NULL UNIQUE,
 subject_id BIGINT NOT NULL, semester_id BIGINT NOT NULL, teacher_id BIGINT NOT NULL,
 capacity INT NOT NULL, schedule_text VARCHAR(200), room VARCHAR(50), status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
 weight1 INT NOT NULL DEFAULT 20, weight2 INT NOT NULL DEFAULT 20, weight_final INT NOT NULL DEFAULT 60,
 grade_locked BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY(subject_id) REFERENCES subjects(id), FOREIGN KEY(semester_id) REFERENCES semesters(id), FOREIGN KEY(teacher_id) REFERENCES teachers(id)
);
CREATE TABLE enrollments (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, student_id BIGINT NOT NULL, section_id BIGINT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(student_id,section_id), FOREIGN KEY(student_id) REFERENCES students(id), FOREIGN KEY(section_id) REFERENCES sections(id)
);
CREATE TABLE scores (
 enrollment_id BIGINT PRIMARY KEY, tx1 DECIMAL(4,2) NOT NULL, tx2 DECIMAL(4,2) NOT NULL, final_score DECIMAL(4,2) NOT NULL,
 total DECIMAL(4,2) NOT NULL, letter VARCHAR(2) NOT NULL, points DECIMAL(2,1) NOT NULL,
 FOREIGN KEY(enrollment_id) REFERENCES enrollments(id)
);
CREATE TABLE audit_logs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, actor VARCHAR(50) NOT NULL, action VARCHAR(60) NOT NULL,
 detail VARCHAR(1500) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_enrollment_section ON enrollments(section_id);
CREATE INDEX idx_section_semester ON sections(semester_id);
CREATE INDEX idx_audit_time ON audit_logs(created_at);
